# 一、归档
# ---------------------------------------------------------------------------
def classify(hit, tags, gaps=None) -> str:
    """决定档位：东西 × 人条件（+ 条件是否已评估）。tags 为当前生效的风险标签。

    顺序即优先级，别随意调（每一步都有实测依据，见模块 docstring）：
      ① 特殊人群 → 需专业确认（整套纪律由医生把关）
      ② 毒性药材 → 明确禁止
      ③ 原处方药 → 需专业确认
      ④ **方向相反 / 明文禁用**（contra 命中，含绝对禁忌状态）→ 明确禁止
      ⑤ 涉及西药相互作用（活血 × 抗凝，**且真的在服**）→ 需专业确认
      ⑥ 命中他的条件 → 对证但有条件
      ⑦ 条件未评估 → 需专业确认（挂起 + 追问）
      ⑧ 无适应症（indication 与他的证候没交集）→ 不建议
      ⑨ 规则本身要求先辨证 / level=high → 需专业确认
      ⑩ 其余 → 可执行

    ④在⑤之前（2026-09-16 第五轮修正）：**禁忌与状态约束的效力高于任何由
    药名触发的分支**。此前⑤在前面且无条件，孕妇问当归（活血类，明文禁忌）
    被压成「需专业确认」——状态识别对了、档位却没跟上，这就是"档位整体变软"
    的根因。⑤在⑥之前：在服抗凝药时用活血类，"方向对但有条件"是不够的。
    """
    d = _as_dict(hit)
    kind = d.get("kind", "")
    sub = d.get("sub", "")
    level = d.get("level", "info")
    cur = set(tags or set())
    cond = set(d.get("tags") or []) & cur

    # 特殊人群：整套纪律，必须由医生把关（不是"禁止吃某样东西"）
    if kind == "population":
        return TIER_CONFIRM
    # 毒性/严格管理药材：自行使用即绝对禁止（与人的条件无关）
    if sub == "toxic":
        return TIER_FORBID
    # 原处方药：不能自行停/减，任何调整需专业确认
    if kind == "drug":
        return TIER_CONFIRM
    # **方向相反 / 明文禁用（属绝对禁忌）→ 明确禁止**。
    # 这一条**必须**在 `_CONFIRM_FIRST` 之前：2026-09-16 第五轮实测退化——
    # 孕妇问当归（活血化瘀类，本条 not_for 明写孕妇禁用）被判成「需专业确认」，
    # 根因是 `_CONFIRM_FIRST` 无条件抢先返回。表现为"状态识别对了、档位没跟上"。
    # 禁忌与状态约束的效力压过一切由"西药相互作用"触发的分支。
    if set(d.get("contra") or []) & cur:
        return TIER_FORBID
    # 涉及西药相互作用的（活血 × 抗凝）：条件再明确也不能自己定。
    # 但**只在真的涉及那类西药时**才成立——原来无条件命中，把所有活血类
    # 压成「需专业确认」，把妊娠禁忌也截胡了。
    _cf = _key_of(d)
    if _cf in _CONFIRM_FIRST and (cur & _CONFIRM_FIRST_TAGS.get(_cf, frozenset())):
        return TIER_CONFIRM
    # 命中"这个人的条件" → 有条件（先满足/先解决，才谈能不能用）
    if cond:
        return TIER_CONDITIONAL
    ind = set(d.get("indication") or [])
    ind_ok = bool(ind & cur)
    # **条件还没评估** → 不许放行（"不知道他有没有湿困"就答"可以吃"，
    # 与"不知道他在不在吃抗凝药就警告出血风险"是同一个错的两面）。
    # 例外：**适应症已经明确对上**（如"乏力+气短+一动就累"问黄芪）时
    # 不再挂起——方向已经成立，剩下没问到的项降级为"顺带问一句"，
    # 否则每个补益类都会被"还缺舌象"卡住，追问变成拦路虎。
    if unassessed(d, gaps, tags) and not ind_ok:
        return TIER_CONFIRM
    # **无适应症** → 不建议（不是有害，是没必要）。判据：这味东西
    # 自带适应症（补益类才有），而用户身上没有任何对应证据，
    # 且上面的关键条件都已评估过（否则应走"挂起+追问"）。
    if ind and not ind_ok:
        return TIER_NOT_INDICATED
    # 规则本身要求先辨证（如参类分品种、活血类要先知道在不在抗凝）→ 需专业确认
    if level == "high" or _key_of(d) in _ALWAYS_CONFIRM:
        return TIER_CONFIRM
    return TIER_OK


def indication_hit(d: dict, tags) -> tuple[list[str], list[str]]:
    """(命中的适应症标签, 缺失的适应症标签)——给出"为什么定这一档"的依据。"""
    ind = set(d.get("indication") or [])
    cur = set(tags or set())
    got = sorted(ind & cur)
    miss = sorted(ind - cur)
    return R.tag_labels(got), R.tag_labels(miss)


def gap_labels(keys) -> list[str]:
    """缺口 key → 人话（"舌象""在服用的药物"…）。

    挂起时必须说清**还差什么**——只说"你还没提到"，用户不知道要补哪一项。
    """
    from app.safety import scripts as SG
    out: list[str] = []
    for g in (keys or []):
        lb = (SG.GAP_ITEMS.get(g) or {}).get("label") or g
        if lb not in out:
            out.append(lb)
    return out


def _set(h, field: str, value) -> None:
    """按对象类型写回：dict 直接赋值，dataclass 用 setattr。

    坑（别改回去）：`_as_dict()` 对 SafetyHit 返回的是 `to_dict()` 的**新字典**，
    往那个字典里写字段，原对象一点没变——分级会静默失效（tier 全是空串）。
    """
    if isinstance(h, dict):
        h[field] = value
    else:
        setattr(h, field, value)


def tier_basis(d: dict, tier: str, tags, gaps) -> str:
    """这一档是**凭什么定下来的**（一句话，给人看也用给模型看）。

    P0-1 的"唯一判定"要求档位可解释：用户看到"不建议（无适应症）"时
    必须能立刻知道依据是"你没有阳虚的表现"而不是"你不能吃"。
    """
    cond = condition_labels(d, tags)
    un = unassessed(d, gaps, tags)
    contra = sorted(set(d.get("contra") or []) & set(tags or set()))
    if tier == TIER_FORBID:
        if contra:
            # 措辞必须跟着语义走：contra 里既有"证候方向相反"，也有
            # "本条明文禁用的人群/慢病"（高血压、孕产）。对孕妇说
            # "你与鹿茸方向相反"是句废话，说"孕产期属本条禁用"她才执行得下去。
            syn = [t for t in contra if t in _SYNDROME_TAGS]
            oth = [t for t in contra if t not in _SYNDROME_TAGS]
            bits = []
            if syn:
                bits.append(f"与你的「{'、'.join(R.tag_labels(syn))}」方向相反")
            if oth:
                bits.append(f"「{'、'.join(R.tag_labels(oth))}」属本条禁用情形")
            return "，且".join(bits) + "（属禁忌）"
        return "属绝对禁忌（毒性药材 / 孕产禁忌），与个人条件无关"
    if tier == TIER_NOT_INDICATED:
        _got, miss = indication_hit(d, tags)
        return ("未见需要它的依据"
                + (f"（它针对的是「{'、'.join(miss)}」）" if miss else ""))
    if tier == TIER_CONFIRM:
        key = _key_of(d)
        # 先给"这一条本身就必须由医生定"的原因——它比"还缺什么"更根本。
        # （实测：气虚的人问人参，依据写成"还缺舌象"会让人以为只要补个舌象
        #   就能自己买来吃；真实原因是参类分温/平/凉三性，必须先分品种。）
        if key in _ALWAYS_CONFIRM:
            return "这一味必须先分品种（红参温 / 生晒参平 / 西洋参凉），须中医师定"
        if un:
            labels = gap_labels(un)
            return ("条件未评估，结论先挂起：还缺"
                    + "、".join(labels or un))
        if cond:
            return f"命中：{'、'.join(cond)}，且这一条必须由医师定"
        if d.get("level") == "high":
            return "峻补 / 高风险之品，须中医师面诊后定"
        return "需舌脉/剂量/配伍判断，不能自行决定"
    if tier == TIER_CONDITIONAL:
        return f"命中：{'、'.join(cond)}" if cond else "方向对，但有需监测的条件"
    return "未命中任何禁忌条件"


def apply_tiers(hits, tags, gaps=None, states=None) -> list:
    """给每个命中打上 tier / tier_label / tier_tone / cond_labels / unassessed_gaps / reading。

    `gaps`：当前仍未掌握的信息缺口（intake.gaps 的产物）。
    它决定"条件未评估"的档位——缺什么，就以什么为准挂起。

    `states`：本轮识别的**状态类约束**（`constraints.detect` 的产物）。
    2026-09-16 第五轮（版本退化修复）：此前状态**只进提示词**，档位判定
    读的是 `scan.tag_from_text` 的 tags——两条链路各算各的，于是出现
    "识别到妊娠、档位却没跟上"。现在把状态折成 tag 并进 `cur`，
    **状态才真正决定档位**（妊娠 × 活血类 → 明确禁止）。

    `reading` 是把这一条**给人看的判读正文**一并算好写回。为什么要在这里算：
    分级结果此前只进了提示词（模型看得到），事件里的 hit 仍带着 rules.py 那个
    按最坏情况写死的 `verdict` —— 于是**用户看到的和模型看到的不是同一段话**，
    前端只能显示"不适合你"这种与本人无关的通用话术。一次算好、两处共用，
    才不会又出现"后端已经条件化了、界面还在念旧台词"。
    """
    from app import constraints as CN
    hs = list(hits or [])
    # 状态约束并入生效标签：这是"状态直接决定档位"的接口。
    cur = set(tags or ()) | CN.state_tags(states)
    for h in hs:
        d = _as_dict(h)
        t = classify(d, cur, gaps)
        _set(h, "tier", t)
        _set(h, "tier_label", TIER_LABEL[t])
        _set(h, "tier_tone", TIER_TONE[t])
        _set(h, "cond_labels", condition_labels(d, cur))
        _set(h, "unassessed_gaps", unassessed(d, gaps, cur))
        _got, miss = indication_hit(d, cur)
        _set(h, "indication_labels", miss)
        # 必须放在上面几个 _set 之后：render 要读刚写进去的 cond_labels/
        # unassessed_gaps，写早了它看到的还是空值（"未评估→挂起"就永不生效）
        _set(h, "reading", render(h, t))
        _set(h, "tier_basis", tier_basis(_as_dict(h), t, cur, gaps))
    hs.sort(key=lambda h: (TIER_SEVERITY.get(_as_dict(h).get("tier", TIER_OK), 9),
                           not _as_dict(h).get("taking")))
    return hs


