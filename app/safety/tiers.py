# 三、档位纪律块：把"唯一判定"从数据变成对模型的要求（P0-1）
# ---------------------------------------------------------------------------
# 为什么必须有这一块：档位算得再准，如果只把"档位名"给模型看，
# 模型仍会按照自己的偏好"补一句操作指南"——实测就是标题写
# 「对证但有条件」、正文写「不能做」、操作指南又写「如果你实在想喝……」。
# 这一块把每档的**必须包含**与**绝不许出现**一起交代下去，
# 让"档位"变成约束，而不只是一个标签。
def tier_discipline_block(hits=None) -> str:
    hs = [_as_dict(h) for h in (hits or [])]
    lines = [
        "【档位纪律：一档一套口径，标题 / 结论 / 操作指南必须同档（P0-1）】",
        "档位是**唯一判定点**：结论句、条件、周期上限、操作指南全部由它派生，"
        "不允许各环节独立表述。实测缺陷就是——标题写「对证但有条件」、"
        "正文写「不能做」、操作指南又写「如果你实在想喝……」："
        "三个环节各说各话，用户不知道到底能不能做。",
    ]
    order = [t for t in TIER_ORDER if any((h.get("tier") or TIER_OK) == t
                                          for h in hs)] or list(TIER_ORDER)
    for t in order:
        spec = TIER_SPEC[t]
        group = [h.get("name", "?") for h in hs
                 if (h.get("tier") or TIER_OK) == t]
        head = f"· 【{TIER_LABEL[t]}】{spec['thesis']}"
        if group:
            head += f"（本轮这一档：{'、'.join(group)}）"
        lines.append(head)
        lines.append(f"    必须包含：{'；'.join(spec['must'])}")
        lines.append(f"    **禁止出现**：{'；'.join(spec['never'])}")
    lines.append("⚠️ 「明确禁止」与「不建议（无适应症）」是**两件事**："
                 "前者是「用了有害」（方向相反 / 绝对禁忌），"
                 "后者是「不必用、没必要」（没有对应的虚证，并非有害）。"
                 "**不许**把「不建议」说成「伤身体」或「有风险」。")
    lines.append("落笔要求：同一件事只给**一个**档位、**一个**结论；"
                 "禁止在同一条里既说不能做、又留一个「少量也行」的口子。")
    return "\n".join(lines)
