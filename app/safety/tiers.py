def unassessed(hit, gaps, tags=None) -> list[str]:
    """该命中关心的条件里，哪些"还没评估"（返回缺口项 key 列表）。

    `tags` 是用户当前生效的标签（可选）。传入它才能识别"反证"（见下）。
    """
    d = _as_dict(hit)
    gaps = set(gaps or ())
    cur = set(tags or ())
    need: list[str] = []
    for t in (d.get("tags") or []):
        # 反证也算"已评估"：规则关心"是不是寒证"（TAG_COLD），而用户已经
        # 明确说出湿热/阴虚的表现时，"有没有寒"这个问题其实已经有答案了。
        # 不认这一点，一杯**对证的**绿豆汤也会因为"没问怕不怕冷"被挂起
        # （实测：湿热人问绿豆，档位被挂到"需专业确认"）。
        if cur & set(_OPPOSED_BY.get(t, ())):
            continue
        for g in _TAG_GAP.get(t, ()):
            if g in gaps and g not in need:
                need.append(g)
    return need


# 与某个 tag 互斥的"反证 tag"：出现即认为该条件已被回答
_OPPOSED_BY: dict[str, tuple[str, ...]] = {
    R.TAG_COLD: (R.TAG_DAMP_HEAT, R.TAG_YIN_DEF),
    R.TAG_DAMP_HEAT: (R.TAG_COLD,),
    R.TAG_YIN_DEF: (R.TAG_DAMPNESS, R.TAG_COLD),
    R.TAG_DAMPNESS: (R.TAG_YIN_DEF,),
}


def _as_dict(h) -> dict:
    """兼容 SafetyHit 对象与（进入共享状态后的）dict。"""
    if isinstance(h, dict):
        return h
    if hasattr(h, "to_dict"):
        return h.to_dict()
    return dict(getattr(h, "__dict__", {}) or {})


def _key_of(d: dict) -> str:
    return (d.get("key") or "").split(":")[-1]


def condition_labels(hit, tags) -> list[str]:
    """该命中"命中了用户的哪些条件"（用于把理由绑到此人的具体情况上）。"""
    d = _as_dict(hit)
    inter = set(d.get("tags") or []) & set(tags or set())
    return R.tag_labels(sorted(inter))


