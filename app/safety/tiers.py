# -*- coding: utf-8 -*-
"""安全分级引擎：把「命中」翻译成**五档处置**，档位由「东西 × 当前人条件」共同决定。

为什么必须分级（架构层问题二）
------------------------------
真实测试暴露的是**两头的错**，而且是同一个系统的两头：

    · 早期「该硬不硬」：用户问「附子能不能自己炖肉吃」，
      回答是「资料库中没有记载，建议问医生」——没有叫停；
    · 后来「该软不软」：用户血虚证明确、无湿象，问阿胶，
      仍被判「不适合」，理由照搬通用话术。

两个方向都失手，说明问题不在「力度调多少」，而在**只有一档**。
所以这里拆成五档：

    明确禁止      命中绝对禁忌/方向相反（毒性药材自行使用、孕产禁忌、寒证喝大寒之品）
    不建议        无适应症：无虚可补、不需要用，**并非有害**（P0-1 新增）
    需专业确认    对证方向存在，但需舌脉/剂量/配伍判断 → 不自行动手，结论挂起
    对证但有条件  方向对，但有需监测的条件 → 可执行 + 停止信号 + 周期上限
    可执行        药食同源、未命中任何禁忌条件 → 给具体做法、频次、周期

判据的关键一句：**「这个东西叫什么」不能单独决定档位**，
必须由「东西 × 当前这个人条件」共同决定。

⚠️ 五档里最容易混的是「明确禁止」与「不建议」——第三轮实测反馈：
鹿茸对**阴虚火旺**者（方向相反，用了有害）与对**25 岁健康人**
（无虚可补，只是不需要）都被答成"不能吃"。两者性质完全不同，
混在一起用户分不清"有害"与"没必要"，也可能因此把"不需要"误当成"伤身"。
分档判据（`classify` 里的顺序即优先级）：

    方向相反（contra × 用户证候）→ 明确禁止
    无适应症（indication 与用户证候没交集，**且信息已够判断**）→ 不建议
    条件没评估（缺舌象/在服药…）→ 需专业确认（挂起 + 追问）

注意「无适应症」排在「条件未评估」**之前**：一个**否定性**结论
（"你没有这个需要"）要求比肯定性结论更多的证据——信息不足时不许下
"不需要"的判词，而要挂起追问（与架构层问题四同一条原则）。

两条配套原则也在本模块落地
--------------------------
① **规则只提供约束，结论由当前条件生成**（架构层问题三）
   原先每条规则挂一段写死的 `verdict`，于是同一味药在相反证型下
   得出**完全相同的结论、一字不差的理由**——那是"关键词 → 固定话术"的
   检索器，不是辨证系统。现在 `render()` 按「用户命中了哪些禁忌条件」
   生成结论：命中 → 有条件的判读；没命中 → 放行并给做法上限。
   检验方法：换一个相反证型问同一味药，结论与理由都必须变。

② **档位是唯一判定点，结论/条件/上限/停止信号全部由它派生**（P0-1）
   实测缺陷：同一条命中被**三个环节各自表述**——标题写"对证但有条件"、
   正文写"不能做"、操作指南又写"如果你实在想喝……"。根因是档位没有
   单一事实来源。现在 `TIER_SPEC` 为每档固定四件套（结论口径 / 必须含 /
   绝不许出现 / 语气），`render()` 与 `tier_discipline_block()` 都从它派生，
   提示词侧还额外禁止"档位之外自留口子"（`never`）。

③ **条件未知时降级为提问，不升级为警告**（架构层问题四）
   「不知道用户用不用抗凝药，就把华法林/阿司匹林整套出血风险搬出来」
   属于"默认最危险"，会吓退正确建议。凡是"档位依赖某个未知条件"的，
   正确动作是把条件落进追问清单（app/inquiry.py），而不是先警告一顿。
"""
