# 条件标签在句子里的写法：把 A/B 选项还原成"实际命中的那个"
def _fill(template: str, cond_labels: list[str], d: dict) -> str:
    """把模板里的 {[标签集]} 占位换成**实际命中的条件标签**。

    模板里的 {[痰湿/湿困]} 只是"这一档涉及的条件集合"，实际渲染时只保留
    用户真正命中的那些——没命中就不该出现在理由里（否则又是"与你无关的话术"）。
    """
    import re
    hits = set(cond_labels)

    def _sub(m):
        options = [o.strip() for o in m.group(1).split("/") if o.strip()]
        got = [o for o in options if o in hits] or options[:1]
        return "、".join(got)

    out = re.sub(r"\{\[([^\]]+)\]\}", _sub, template)
    why = (d.get("why") or "").strip()
    if why and "{why}" in out:
        out = out.replace("{why}", why + " ")
    else:
        out = out.replace("{why}", why + " " if why else "")
    not_for = (d.get("not_for") or "").strip()
    out = out.replace("{extra}", (f" 尤其注意：{not_for} " if not_for else ""))
    cond = "、".join(cond_labels) or "需要监测的条件"
    out = out.replace("{cond}", cond)
    return out.strip()


def render(hit, tier: str | None = None) -> str:
    """按「档位 × 命中条件」生成该条的判读结论（不再用写死的 verdict）。

    三种情形：
      ① 条件已命中（cond_labels 非空）→ 走该档模板，理由绑定用户的具体条件；
      ② 条件**未评估**（unassessed_gaps 非空）→ 明确说"先别急着用，取决于 X，
         你还没说"，把结论挂起（配合 inquiry 的追问，不凭空放行也不凭空警告）；
      ③ 其余 → 该档模板；模板缺失时退到规则自带的 verdict，再不行用通用兜底。
    """
    d = _as_dict(hit)
    tier = tier or d.get("tier") or classify(d, set())
    # 注意：这里**不能**在 cond_labels 为空时去拿"药自身的 tags"顶上——
    # 那是"这个东西关心什么"，不是"这个人命中了什么"。早先这么写过，
    # 结果"条件未评估"的分支永远进不去（conds 恒为真），
    # 表现为：用户什么都没说，阿胶照样给出"你先化湿"的判读。
    conds = list(d.get("cond_labels") or [])
    tpl = _TEMPLATES.get(_key_of(d), {})

    # ② 条件未评估：把结论挂起（这是"缺口 → 追问"而不是"缺口 → 保守默认"的落点）
    if tier == TIER_CONFIRM and not conds and d.get("unassessed_gaps"):
        # 必须点名"还差什么"——早先写成"取决于高血压、阴虚、湿热这几项"，
        # 那是**这味药关心什么**，不是"你还没说什么"，用户看完仍不知道答哪题。
        need = gap_labels(d.get("unassessed_gaps"))
        return (f"**先别急着用，这一条我还判断不了**。它还取决于"
                f"「{'、'.join(need)}」——{'这些' if len(need) > 1 else '这一项'}"
                f"你还没提到。**结论先挂起**："
                f"把下面几个问题答一下，方向立刻就能定，不用先买来试。")

    if tier in tpl:
        return _fill(tpl[tier], conds, d)
    # 模板里没有这一档 → 该档的**派生兜底**（结论/条件/上限/停止信号齐备）。
    # 规则里那段写死的 verdict **只在"对证但有条件 / 需专业确认 / 可执行"三档**
    # 才允许回退使用：那些文本多数是按"命中条件"的口吻写的。
    # 对「明确禁止」「不建议」两档一律不再回退——实测事故就是附子那段的
    # verdict 写着"你正在服用降压药"，于是没吃降压药的人也被安上这份前提。
    # （不再加「[档位]」前缀——调用方本来就会单独 display 档位名，会叠字。）
    if (not tpl and (d.get("verdict") or "").strip()
            and tier in (TIER_CONFIRM, TIER_CONDITIONAL, TIER_OK)):
        return _fill(d["verdict"], conds, d)
    return _fill(_FALLBACK.get(tier, _FALLBACK[TIER_OK]), conds, d)


def summarize(hits) -> list[dict]:
    """给前端/事件用的分级摘要：[{key,name,tier,tier_label,cond_labels,basis}]。"""
    out = []
    for h in (hits or []):
        d = _as_dict(h)
        out.append({"key": d.get("key"), "name": d.get("name"),
                    "tier": d.get("tier"),
                    "tier_label": d.get("tier_label"),
                    "cond_labels": d.get("cond_labels") or [],
                    "basis": d.get("tier_basis") or ""})
    return out


def tier_counts(hits) -> dict[str, int]:
    """本轮各档位各几条（前端头部计数、完整性自检都用它）。"""
    out: dict[str, int] = {}
    for h in (hits or []):
        t = _as_dict(h).get("tier") or TIER_OK
        out[t] = out.get(t, 0) + 1
    return out


