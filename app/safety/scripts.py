def gap_block(gaps: list[str], need_consult: bool = True) -> str:
    """信息不足时的强制追问块。"""
    if not gaps:
        return ""
    lines = ["【信息不足：本轮必须走追问分支】",
             "缺少以下关键信息，**本轮不得给出方剂级内容、不得给出具体药材与用量、"
             "不得下证型结论**："]
    for g in gaps:
        it = GAP_ITEMS.get(g)
        if it:
            lines.append(f"· 缺 {it['label']}")
    lines.append("")
    lines.append("请在回答结尾提出 2~3 个**聚焦追问**（不要一次问一长串），"
                 "优先问上面缺的项，用口语化的问法，例如：")
    picked = [GAP_ITEMS[g]["ask"] for g in gaps[:3] if g in GAP_ITEMS]
    for p in picked:
        lines.append(f"  - {p}")
    lines.append("可以先给**不依赖这些信息的通用安全建议**"
                 "（作息、饮食有节、避免久坐），但不要越过追问去开方。")
    return "\n".join(lines)


