def tag_labels(tags) -> list[str]:
    """把 tag 集合转成人类可读的人群名（去重保序）。"""
    out: list[str] = []
    for t in tags:
        lb = TAG_LABEL.get(t)
        if lb and lb not in out:
            out.append(lb)
    return out
