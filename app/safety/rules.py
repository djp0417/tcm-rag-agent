"""安全规则库（硬编码数据层）：**刻意独立于 RAG**。

为什么要独立于知识库
--------------------
实测事故（2026-09-15，用户真机对话）：用户自述「45 岁女性、高血压、每天吃氨氯地平、
自己买了附子理中丸、天天喝红豆薏米茶、早上生姜红枣茶、朋友推荐吃阿胶」，
问「这些能一起吃吗、会不会和降压药冲突」。
当时的回答是**逐条检索资料库后如实说"资料库里没有这方面的记载"**——
从"不编造"的角度没错，但从**安全**角度是失败的：

    安全结论不该依赖"资料库里有没有写过"。
    附子有毒、甘草升血压、活血药加抗凝药出血风险——
    这些是**确定的药学事实**，不该因为语料没覆盖就不再提醒。

所以本层与 RAG 彻底解耦：
  · 数据是硬编码的结构化规则（不检索、不问模型、不看置信度）；
  · 命中即**优先路由**——在 LLM 生成之前就注入强制结论；
  · 语料可以缺，规则不能缺。

三层结构
--------
    rules.py    本文件：规则数据（药材 / 西药 / 特殊人群 / 食药同源）
    scan.py     扫描器：从文本与用户档案里找出命中的规则
    scripts.py  话术模板：把命中项渲染成"所以对你而言…"的判读结论

与 app/multiagent/checks.py 的分工
----------------------------------
`checks.py` 管的是**输出侧合规**（疗效承诺、疾病诊断这类"说了什么"的越界）；
本文件管的是**输入端风险识别**（用户提到的药材/西药/人群"涉及什么"）。
两者在流水线里都要跑，前者在 safety 节点，后者在 router 节点。
"""
