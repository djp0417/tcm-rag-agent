@dataclass(frozen=True)
class HerbRule:
    """一条「药材/食材」规则。

    kind：toxic=毒性或需严格控量的药材；herb=需辨证使用的药材；
          food=食药同源（可日常吃，但有体质宜忌）。
    level：high=必须叫停；medium=需先确认（结合体质/慢病）；info=提示。
    """
    key: str
    name: str
    aliases: tuple[str, ...]
    kind: str
    level: str
    why: str            # 客观药性 / 风险机制（可直接引用给用户）
    not_for: str        # 哪类人不能吃 / 不宜吃
    verdict: str        # 「所以对你而言」的模板（{who} 会被替换成具体命中人群）
    tags: tuple[str, ...] = ()
    # ---- 2026-09-16 第三轮新增：把「档位」从"有没有命中条件"细化为三种语义 ----
    # `contra`：**方向相反**的证候 → 用了有害 → 明确禁止（禁忌）。
    #           例：鹿茸 × 阴虚火旺/湿热 —— 温燥峻补碰上热象，是火上浇油。
    # `indication`：这味东西**是给什么用的**（适应症）。一个补益类药食，
    #           若用户身上没有任何对应"虚"的证据，正确定档是
    #           **不建议（无适应症）**——不是有害，是没必要；
    #           这与"方向相反"必须给出完全不同的结论与说辞。
    #           留空 = 不做"无适应症"判断（食药同源的日常食材不适用）。
    contra: tuple[str, ...] = ()
    indication: tuple[str, ...] = ()


@dataclass(frozen=True)
class DrugRule:
    """一类西药 → 需要知道的冲突与纪律。

    must_say 是**强制话术**：命中即原样（或近义）出现在回答里，不允许省略。
    """
    key: str
    cls: str
    aliases: tuple[str, ...]
    conflicts: tuple[str, ...]      # 与之相关的药材/食材关键词
    must_say: str
    tags: tuple[str, ...] = ()


@dataclass(frozen=True)
class PopulationRule:
    """特殊人群：命中即整套禁忌提醒。"""
    key: str
    name: str
    aliases: tuple[str, ...]
    must_say: str
    tags: tuple[str, ...] = ()


