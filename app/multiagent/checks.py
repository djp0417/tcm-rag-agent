# 五、与硬规则命中冲突（跨层一致性）
# ---------------------------------------------------------------------------
# 常见成药/方剂 → 组成药材（部分）：2026-09-15 测试缺陷——前脚说
# "含甘草制剂与降压冲突"，后脚把同样含甘草的参苓白术散当建议引用，
# 规则层却没报：因为规则命中的是「甘草」这个名字，方案里写的是方剂名。
# 方剂名必须先展开成成分再扫，跨层一致性才不会从名字的缝里漏过去。
