# -*- coding: utf-8 -*-
"""确定性安全护栏：不依赖模型的规则层。

为什么要在"审查 Agent"之外再加一层规则
--------------------------------------
安全审查节点是 LLM，而 LLM 有两个不可接受的性质：
  ① **不完全可控**——同一个提示词，绝大多数时候能拦住，但偶尔会放行；
  ② **不可复现**——temperature=0 也只是"基本确定"，不是"一定"。
安全这件事上，**宁可把模型的自由度再砍一刀**。所以分两层：

    规则层（本文件）  ：只管"零歧义"的模式，命中就直接定罪，不看模型脸色；
    LLM 审查节点      ：管需要上下文判断的部分（证型与方案是否矛盾、
                        引用是否挂羊头卖狗肉、红旗信号是否被忽略）。

分界线怎么画：**规则只对"出现即违规"的模式直接定罪**——
疗效承诺（"三天根治"）和疾病诊断（"您患有慢性胃炎"）无论上下文如何都是越界；
而"剂量""毒性药材"这类**存在合法上下文**（禁忌提醒里就会出现药材名），
规则只把它们当**线索**交给 LLM 结合语境判断，避免"一提到附子就否决"
把正常方案也拦下来。

这也解释了红旗症状为什么要放在**路由**层而不是审查层：路由节点在用户
提问的**当轮**就短路，比等整条链路跑完再否决要省得多，也更安全。
"""
from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# 一、红旗症状（路由层短路用）
# ---------------------------------------------------------------------------
# 收录原则：出现这些词时，"该不该建议就医"的答案几乎不依赖于中医辨证——
# 也就是说，这是一批**不需要专业判断就该转诊**的信号。
RED_FLAG_KEYWORDS: tuple[str, ...] = (
    # 一般性危险信号
    "消瘦", "暴瘦", "体重下降", "体重减轻", "明显变瘦",
    "胸痛", "胸闷痛", "心口痛", "心绞痛", "心悸不止",
    "便血", "血便", "黑便", "咯血", "咳血", "呕血", "吐血", "尿血",
    "不明原因发热", "持续发热", "长期低烧", "反复发烧", "持续高烧",
    "肿块", "包块", "结节", "肿瘤", "癌", "恶性",
    "呼吸困难", "喘不上气", "窒息", "晕厥", "昏迷", "抽搐", "突然倒地",
    "剧烈疼痛", "疼得受不了", "痛得受不了",
    # 特殊人群与用药人群
    "怀孕", "孕妇", "妊娠", "哺乳期", "备孕", "胎儿",
    "婴幼儿", "新生儿", "小孩几岁",
    "长期服药", "正在吃药", "正在用药", "化疗", "放疗", "术后", "支架",
    "糖尿病", "高血压", "心脏病", "甲亢", "甲减", "肝硬化", "肾功能不全",
    "抑郁症", "焦虑症", "精神类",
    # 直接求诊断 / 求药
    "我是不是得了", "帮我诊断", "开个方子", "给我开药", "开点药",
)

# 单独出现"痛"不算红旗——"我经常头痛"是养生咨询的常见起点，
# 一律转诊会让系统变得没用。**只有"疼痛 + 剧烈/持续/加重"这类限定才转**，
# 这条边界是刻意留的，宁可少拦一点，也不要让系统变成"什么都不敢答"。
_RED_FLAG_RE = re.compile("|".join(re.escape(k) for k in RED_FLAG_KEYWORDS))


def scan_red_flags(text: str) -> list[str]:
    """返回命中的红旗关键词（可能多个）。"""
    return sorted({m.group(0) for m in _RED_FLAG_RE.finditer(text or "")})


# ---------------------------------------------------------------------------
# 二、零歧义模式：命中即违规
# ---------------------------------------------------------------------------
_CURE_CLAIMS = (
    "根治", "包治", "包好", "彻底治愈", "彻底根治", "药到病除",
    "立竿见影", "保证治好", "保证有效", "三天见效", "一周见效",
    "七天见效", "无副作用", "百分百",
)

_DIAGNOSIS_CLAIMS = (
    "确诊", "诊断为", "你患有", "你已经得了", "你这就是典型的",
)

# 「禁/忌/不宜/勿」出现在同句时，说明这是在**提醒不要用**，不是推荐——
# 这是"剂量/药材"类线索必须做的语境豁免，否则正常的禁忌条目会被误判。
_NEGATION = ("忌", "禁", "不宜", "勿", "避免", "少用", "慎用")

# 「依从性/纪律」语境：句子里出现这些词，说明是在**提醒守住正在用的药**
# （不能自行停减、遵医嘱、告知医生药师、不可替代……），而不是在推荐用它。
# 2026-09-16 真事故：用户在服降压药时，方案写「守住降压药纪律与基础排查——
# 调理是配合，不是替代」，被 safety_conflicts 判成"把降压药当建议写入"→
# 规则层 high 冲突 → 必然打回重写 ×2 → **必然降级**，三专家产出永远到不了
# 用户手上。凡"在服西药"的用户都会中这个招，属确定性误判（不是模型偶发）。
_COMPLIANCE = (
    "纪律", "不能自行停", "不可自行停", "自行停药", "自行停用", "自行减量",
    "自行减药", "遵医嘱", "按医嘱", "告知医生", "告诉医生", "咨询医生",
    "咨询医师", "药师", "不能替代", "不可替代", "不是替代", "替代不了",
)


def _is_compliance_context(sent: str) -> bool:
    """句子里是否在讲"守住正在服的药/别自行停减/听医生的"（而非推荐用它）。"""
    return any(tok in sent for tok in _COMPLIANCE)


def _split_sentences(text: str) -> list[str]:
    """按中英文句读断句（规则扫描的判断单位是句子，不是整篇）。"""
    parts = re.split(r"[。！？；;\n\r]+", text or "")
    return [p.strip() for p in parts if p.strip()]


def hard_violations(text: str) -> list[dict]:
    """零歧义违规：疗效承诺 + 疾病诊断。命中即定罪，不问模型。"""
    out: list[dict] = []
    for sent in _split_sentences(text):
        for kw in _CURE_CLAIMS:
            if kw in sent:
                out.append({"type": "越界", "by": "rule", "severity": "high",
                            "detail": f"出现疗效承诺「{kw}」：{sent[:60]}"})
                break
        for kw in _DIAGNOSIS_CLAIMS:
            if kw in sent:
                out.append({"type": "越界", "by": "rule", "severity": "high",
                            "detail": f"出现疾病诊断式表述「{kw}」：{sent[:60]}"})
                break
    return out


# ---------------------------------------------------------------------------
# 三、软线索：交给 LLM 结合语境判断
# ---------------------------------------------------------------------------
_DOSE_RE = re.compile(r"\d+\s*(?:克|g|G|毫克|mg|钱|剂|毫升|ml|ML)")

_RESTRICTED_HERBS = (
    "附子", "川乌", "草乌", "马钱子", "巴豆", "甘遂", "大戟", "芫花",
    "雷公藤", "朱砂", "雄黄", "蟾酥", "洋金花", "罂粟", "硫黄", "水银", "铅丹",
)


def soft_hints(text: str) -> list[str]:
    """给出"值得看一眼"的线索（不是结论），供 LLM 审查时参考。"""
    hints: list[str] = []
    for sent in _split_sentences(text):
        if any(neg in sent for neg in _NEGATION):
            continue                       # 禁忌句里的药材名/剂量不算线索
        if _DOSE_RE.search(sent):
            hints.append(f"疑似给出用量：{sent[:60]}")
        for herb in _RESTRICTED_HERBS:
            if herb in sent:
                hints.append(f"疑似提到毒性/处方药材「{herb}」：{sent[:60]}")
                break
    return hints


def rule_scan(text: str) -> dict:
    """规则层总入口：返回 {"violations": [...], "hints": [...]}。"""
    return {"violations": hard_violations(text), "hints": soft_hints(text)}


# ---------------------------------------------------------------------------
# 四、只引不判（引用必须带判读结论）
# ---------------------------------------------------------------------------
# 用户实测的原话是：「资料里说 X，但资料库里没有针对你个人情况的方案」——
# 把原文摆出来就结束，知识展示了，但**服务没完成**。
# 判据刻意做得很宽松（只要出现任何一个判读词就算给了判读），
# 因为这一层的目的是"兜住彻底没判读的情况"，不是挑剔措辞。
_JUDGMENT_MARKS = (
    "所以对你而言", "对你而言", "对你来说", "你能做", "能做", "不能做",
    "需先确认", "先确认", "不建议", "建议先", "可以吃", "不适合", "适合你",
    "可以少量", "暂停", "别吃", "不要吃", "可以留", "换成",
)

_CITE_RE = re.compile(r"《[^》]{1,24}》|引文|原文|\"quote\"")


def has_citation(text: str) -> bool:
    """文本里是否出现了引用（书名号 / 引文标记 / evidence quote 字段）。"""
    return bool(_CITE_RE.search(text or ""))


def has_judgment(text: str) -> bool:
    """文本里是否给出了对用户本人的判读结论。"""
    t = text or ""
    return any(m in t for m in _JUDGMENT_MARKS)


def judgment_violations(text: str) -> list[dict]:
    """只引不判：有引用、却没有任何判读结论。"""
    if has_citation(text) and not has_judgment(text):
        return [{"type": "只引不判", "by": "rule", "severity": "medium",
                 "detail": "引用了资料/原文，但通篇没有给出"
                           "「所以对你而言：能做 / 不能做 / 需先确认」的判读。"}]
    return []


