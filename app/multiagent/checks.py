def _expand_formula_herbs(text: str) -> list[str]:
    """把文本里**非禁忌句**出现的方剂名展开成组成药材（白名单内）。

    为什么只展开非禁忌句：方案写「忌参苓白术散」是在提醒不要用，
    展开它的成分去报冲突就是误报——负责任的是"作为建议出现"的那部分。
    """
    herbs: list[str] = []
    for sent in _split_sentences(text or ""):
        if any(neg in sent for neg in _NEGATION):
            continue
        if _is_compliance_context(sent):
            continue                       # "守住降压药纪律"不是在建议用药
        for formula, parts in _FORMULA_HERBS:
            if formula in sent:
                herbs.extend(parts)
    return sorted(set(herbs))


def safety_conflicts(plan_text: str, hits: list[dict]) -> list[dict]:
    """安全规则命中的高危项，是否被当成"建议"写进了方案。

    与 soft_hints 的区别：soft_hints 是"提到毒性药材就提示看一眼"，
    这里更硬——**结合用户档案**已经判定"这人对这味药有风险"
    （例如高血压 + 甘草、痰湿 + 阿胶），如果方案里还出现它且不在
    禁忌语境中，就是跨层冲突，直接定罪。
    每味药最多报一条（命中即停），避免刷屏。
    """
    out: list[dict] = []
    # 方剂展开：方案文本里出现的方剂名 → 组成药材并入扫描文本，
    # 这样「参苓白术散」就能被「甘草」的命中规则抓到
    expanded = (plan_text or "") + "。" + "、".join(
        _expand_formula_herbs(plan_text))
    for h in (hits or []):
        if h.get("level") != "high":
            continue
        # 处方西药（用户在服）：方案提到它只能是「守住纪律 / 别自行停减」，
        # **不存在"被方案推荐"这种可能**（处方药由医生开）。按"建议写入"定罪
        # 是确定性误判——2026-09-16 真事故：方案写「你有高血压在服氨氯地平，
        # 控盐是基础」，被判成"把降压药当建议写入"→ high 冲突 → 打回重写 ×2
        # → 必然降级；凡在服西药的用户都中招，三专家产出永远到不了用户手上。
        if h.get("kind") == "drug" and h.get("taking"):
            continue
        # "薏米（薏苡仁）"这类展示名去掉括号，用主名匹配
        names = [(h.get("name") or "").split("（")[0].strip(),
                 (h.get("matched") or "").strip()]
        names = [n for n in names if n]
        for sent in _split_sentences(expanded):
            if any(neg in sent for neg in _NEGATION):
                continue                     # 禁忌句里出现是正常的
            if _is_compliance_context(sent):
                continue                     # 依从性提醒（别自行停/遵医嘱）不是建议
            if any(n in sent for n in names):
                out.append({
                    "type": "冲突", "by": "rule", "severity": "high",
                    "detail": f"安全规则已判定用户不宜使用「{names[0]}」，"
                              f"但方案里把它当作建议写入：{sent[:60]}"})
                break
    return out
