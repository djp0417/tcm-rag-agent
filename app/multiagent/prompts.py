# 为什么把原来一个大 planner 拆成三个专家
# ---------------------------------------
# 原来 planner 一个节点要同时产出食疗 / 起居 / 导引 / 穴位 / 禁忌五类内容，
# 提示词里塞了五套规矩，结果是"每类都给一点、每类都不深"：
# 食疗只写到"少食生冷黏腻"这种放之四海皆准的话，没有"炒薏米替生薏米"
# 这样的可执行替代；穴位永远只有"足三里"一个。
# 拆成三个专家后，每个节点只服务一个目标，提示词短、要求具体，
# 而且**三个专家的检索词互不干扰**（食疗查食材性味，经络查穴位主治，
# 运动查导引功法），比原来"一句话混检"召回质量高得多。
#
# 统一约定：每个专家都要把条目挂回「本虚 / 标实」，
# 这样才能被主控汇总成分层结论，而不是三份并列清单。

