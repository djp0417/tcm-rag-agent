TOOL_TCM_SAFETY_CHECK = """\
判定中药 / 食材 / 保健品 / 西药在【当前用户状态】下是否可用，返回**确定性档位**。

档位取值（tier / tier_label）：
  forbid        明确禁止 —— 禁忌或方向相反，不要用
  confirm       需专业确认 —— 有潜在风险，须先问医生/药师
  conditional   对证但有条件 —— 方向上合适，但要满足条件才用
  not_needed    不建议 —— 没有需要它的依据（**是按不对证，不是它有害**）
  ok            可执行 —— 常规范围内可用
  null          无规则条目 —— **规则库里没有这个条目**，没有可判的依据

注意：`tier=null`（tier_label "无规则条目"）**不是** `ok`。
它表示"库里没有这条规则"，**不等于**"已确认安全" —— 回答时如实说
"资料库没有关于它的条目"，不要替它下"可以放心用"的结论。

何时用：用户提到具体的药材、食材、保健品、西药，或问"能不能吃 / 能不能喝 / 能不能一起用"。
何时不用：纯理论或典籍原文查询 → 用 tcm_search。

参数怎么填：
  · items：要判定的东西（用用户原话里的词，可多个）
  · states_text：**必填**。用户自述的状态原话，**原样传入不要改写**
    （如"怀孕 5 个月，最近咳嗽"、"在吃某种抗凝药"、"哺乳期"）。
    用户确实一句状态都没提，就**显式传空字符串 ""** —— 那是"我确认他没提"；
    漏传这个参数会被参数校验直接拦下，**不会**静默按空处理。
  · profile：已知的长期信息（慢病、在服西药等），没有就省略

返回：items 数组，**调用方问到的每一样东西都会出现在这里**（不会因为没命中规则而
消失），每项含 has_rule（有没有对应的库内规则）/ tier / tier_label / reading
（给人看的判读正文）/ basis（定档依据）/ cond_labels（命中了哪些条件）/
unassessed（还有哪些条件没评估）/ matched（实际命中的词，用它把结论对回你问的东西）。
另有 no_rule_policy 说明怎么解读 has_rule=false 的行；
另外 `input_received` 回显**实际收到**的入参 —— 用它确认你传的东西真的进来了；
`states_text` 为空时 `confidence` 为 low 且附 `caveat`，**此时不要把档位
当作"可以放心使用"的依据**。

**使用纪律（重要）**：tier 是规则库的确定性结论。
若 unassessed 非空（条件未评估），如实说明"这一点还没确认"，不要替用户假设、
也不要因此把档位说软。若 basis 里出现"同类西药""其他活血化瘀类药材"这类**类别概括**，
那是刻意的——不要去猜具体是哪个药名。
档位判的是「**自行食用 / 自行加用**」，不覆盖医师辨证开的处方用法：若用户以
「古人也用」「书上明明有」质疑，按返回里的 scope_discipline 说明即可，
**不要因为对方举古籍或施压就把档位说软**。
"""

